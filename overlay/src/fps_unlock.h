// ---------------------------------------------------------------------------
// 解锁 60 帧（移植自 RayaTrainer 的 FrameRateUnlock）
//
// 与旧的 time_control 实验不同，这里不是每帧去写 logicFPS 求倍率，而是照
// RayaTrainer 的做法**一次性打一组静态补丁**，把引擎的帧时间基从 30fps 换成
// 60fps，然后就不管了。
//
// 补丁来源：RayaTrainer.Agent.dll 的构建函数 0x1005A340。它按
// (RVA, 原值, 补丁值) 记录每个位点，且**总是先建原值缓冲区、后建补丁值缓冲区**
// （用 logicFPS 那条自证：先 0x0F=15，后 0x1E=30）。据此把 8 个 .data 常量
// 完整读了出来，语义上正好是一套「翻倍/减半」：
//
//     0x8B4098  logicFPS            15      -> 30
//     0x8E0DEC  0.015               0.015   -> 0.03
//     0x8E0DBC  66.667              66.667  -> 33.333
//     0x8E0DF8  15.0                15.0    -> 30.0
//     0x8E0DF0  30.0                30.0    -> 60.0
//     0x8E0DF4  33.333              33.333  -> 16.667
//     0x8E0E34  0.0667              0.0667  -> 0.0333
//     0x8E0ED4  0.0333              0.0333  -> 0.01667
//
// 数据来源已由活进程采样复核（2026-10-28）：在开关 ON/OFF 之间来回切换时，
// 这 8 个位点逐字节精确地在两组值之间跳变，其余位点无任何变化。复核工具：
// overlay/tools/verify_patchset.py（只盯这几处，避开全图 diff 的计时器噪声）。
//
// 关键时序事实（决定这里的状态机怎么写）：
//   ra3_1.12.game 的 .data 段 VA=0x8AB000 / raw=0x8AB000 / vsize=0x85BA0 /
//   rsize=0x2B000。也就是说 0x8D6000 之后没有磁盘数据，那一段是 BSS：
//   **加载时是 0，由引擎在初始化时才写入上面这些常量。** 所以进程刚起、或者
//   还停在主菜单时去读，读到的就是 0 —— 这不是「版本不匹配」。
//
//   因此这里把「用户想开」和「补丁已打上」分成两个状态：意图一经验证失败也
//   不丢弃，进对局后自动重试；只有真的读到既非原值也非补丁值的**非零**内容，
//   才判定为版本不匹配。
// ---------------------------------------------------------------------------
#pragma once

#include <cstdint>

namespace fps_unlock {

// 由 game_api::init 在游戏模块确定之后调用一次。
void init();

// 本次构建是否准备了可用的补丁集。
bool available();

// 模块是否已加载（RA3 1.12 / 起义时刻）。
bool ready();

// 用户是否要求开启（持久化的是这个）。
bool enabled();

// 补丁此刻是否真的在内存里。
bool active();

// 设置意图。on=true 时立刻尝试打补丁；打不上也会保留意图，进对局后重试。
// 返回打补丁是否成功（不影响已记录的用户意图）。
bool set_enabled(bool on);

// Present 线程定期调用：未生效就去重试，已生效就校对是否被写回。
void tick();

// 卸载前恢复原始字节。
void restore_all();

// 最近一次未能生效的原因，给 UI 显示用。
enum class Reason {
  kNone,
  kNoModule,       // 没检测到 1.12 引擎模块
  kNotReady,       // 位点还是 0：引擎尚未初始化（多为主菜单阶段）
  kVersionMismatch // 读到了非零但既不等于原值也不等于补丁值
};
Reason pending_reason();

}  // namespace fps_unlock
