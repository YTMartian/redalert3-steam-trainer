"""Generate the C++ patch tables for fps_unlock.cpp from the captured JSON.

Hand-transcribing 20+ byte blobs is how silent corruption happens, so the tables
are emitted mechanically from raya_full_patchset.json.

Only regions whose destination is inside the engine image are emitted. The other
42 hooks jump into memory RayaTrainer VirtualAlloc'd itself, so replaying them
without the trainer's code would jump into unmapped pages and crash -- they are
listed separately and skipped on purpose.

Writes fps_unlock_patchset.inc next to the overlay sources.
"""
from __future__ import annotations

import json
import struct
import sys
from pathlib import Path

BASE = 0x400000
IMG_LO, IMG_HI = 0x400000, 0x400000 + 0x950000

# The trampoline handed to the JMP at 0x31F457. Written into the zero padding at
# the end of .text, exactly where RayaTrainer puts it, so the absolute operands
# inside it (0xBC6440 / the jmp back) stay valid.
CAVE_RVA = 0x7C6420

SKIP_INPLACE = {
    # 0x1D -> 0x10 immediates and a jae->jmp flip belong to other trainer
    # features, not to the frame-rate unlock.
    0x23DC21, 0x23DC33, 0x268783,
    # jumps into trainer-allocated memory
    0x348990,
}


def classify(live: bytes) -> str:
    if live[:1] == b"\xE9" and len(live) >= 5:
        rel = struct.unpack("<i", live[1:5])[0]
        tgt = BASE + 0  # placeholder, caller passes rva
        return "jmp"
    return "other"


def emit_bytes(name: str, data: bytes, indent: str = "    ") -> str:
    lines = []
    for i in range(0, len(data), 12):
        chunk = data[i:i + 12]
        lines.append(indent + " " + ", ".join(f"0x{b:02X}" for b in chunk) + ",")
    return f"{indent}/* {name} */\n" + "\n".join(lines)


def main() -> int:
    src = Path("raya_full_patchset.json")
    if not src.exists():
        print("run capture_vs_disk.py first")
        return 1
    patches = json.loads(src.read_text(encoding="utf-8"))["patches"]

    portable = []
    skipped = []
    for p in patches:
        rva = int(p["rva"], 16)
        live = bytes.fromhex(p["live"])
        disk = bytes.fromhex(p["disk"])

        if rva == CAVE_RVA:
            portable.append((rva, disk, live, "cave"))
            continue
        if rva in SKIP_INPLACE:
            skipped.append((rva, "other feature"))
            continue

        if live[:1] == b"\xE9" and len(live) >= 5:
            rel = struct.unpack("<i", live[1:5])[0]
            tgt = BASE + rva + 5 + rel
            if IMG_LO <= tgt < IMG_HI:
                portable.append((rva, disk, live, "jmp"))
            else:
                skipped.append((rva, f"jmp -> {tgt:#x} (trainer memory)"))
            continue

        if len(live) == 3:
            new = int.from_bytes(live, "little")
            old = int.from_bytes(disk, "little")
            if IMG_LO <= new < IMG_HI:
                portable.append((rva, disk, live, f"ptr {old:#x}->{new:#x}"))
            else:
                skipped.append((rva, f"ptr -> {new:#x}"))
            continue

        # Longer in-place runs, e.g. 0x22A756 with two absolute operands.
        if rva == 0x22A756:
            portable.append((rva, disk, live, "ptr x2"))
            continue

        skipped.append((rva, "unclassified"))

    # Cave must be written first, before anything jumps into it.
    portable.sort(key=lambda t: (0 if t[3] == "cave" else 1, t[0]))

    out = []
    out.append("// ---------------------------------------------------------------------------")
    out.append("// GENERATED by overlay/tools/gen_patchset_inc.py -- do not hand-edit.")
    out.append("// Source: raya_full_patchset.json, captured from a live ra3_1.12.game")
    out.append("// process with RayaTrainer's 60fps unlock ON.")
    out.append("//")
    out.append(f"// {len(portable)} portable region(s) emitted, {len(skipped)} skipped")
    out.append("// (skipped ones jump into memory RayaTrainer allocated itself).")
    out.append("// ---------------------------------------------------------------------------")
    out.append("")

    names = []
    for i, (rva, before, after, why) in enumerate(portable):
        bname = f"kBlob{i}_before"
        aname = f"kBlob{i}_after"
        names.append((rva, len(after), bname, aname, why))
        out.append(f"// {rva:#08x}  len={len(after)}  ({why})")
        out.append(f"const uint8_t {bname}[{len(before)}] = {{")
        out.append(emit_bytes("original", before))
        out.append("};")
        out.append(f"const uint8_t {aname}[{len(after)}] = {{")
        out.append(emit_bytes("patched", after))
        out.append("};")
        out.append("")

    out.append("const PatchEntry kCodePatches[] = {")
    for rva, ln, bname, aname, why in names:
        out.append(f"    {{{rva:#010x}, {ln}, {bname}, {aname}}},  // {why}")
    out.append("};")
    out.append("constexpr int kCodePatchCount =")
    out.append("    (int)(sizeof(kCodePatches) / sizeof(kCodePatches[0]));")
    out.append("")

    dst = Path(__file__).resolve().parent.parent / "src" / "fps_unlock_patchset.inc"
    dst.write_text("\n".join(out), encoding="utf-8")
    print(f"wrote {dst}")
    print(f"  portable: {len(portable)}")
    for rva, ln, _b, _a, why in names:
        print(f"    {rva:#08x} len={ln:<3} {why}")
    print(f"  skipped:  {len(skipped)}")
    for rva, why in skipped:
        print(f"    {rva:#08x} {why}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
